CREATE TABLE METODO_PAGO
(
  IdMetodo INT IDENTITY(1,1) NOT NULL, 
  Descripcion VARCHAR(50) NOT NULL,
  CONSTRAINT PK_METODO_PAGO PRIMARY KEY (PK_METODO_PAGO)
);

CREATE TABLE CLIENTE
(
  Dni INT NOT NULL, -- NO lleva IDENTITY (es un dato real)
  Nombre VARCHAR(50) NOT NULL,
  Apellido VARCHAR(50) NOT NULL,
  Telefono VARCHAR(20) NOT NULL,
  Calle VARCHAR(50) NOT NULL,
  Altura INT NOT NULL,
  Localidad VARCHAR(50) NOT NULL,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (DNI)
);

CREATE TABLE VENTA
(
  NroComprobante INT IDENTITY(1,1) NOT NULL, 
  Fecha DATETIME NOT NULL,
  Dni INT NOT NULL,
  CONSTRAINT PK_VENTA PRIMARY KEY (Nro_Comprobante),
  CONSTRAINT FK_VENTA_CLIENTE FOREIGN KEY (DNI) REFERENCES CLIENTE(DNI)
    ON DELETE NO ACTION
    ON UPDATE CASCADE, 
  CONSTRAINT CHK_VENTA_Fecha CHECK (Fecha <= GETDATE())
);

CREATE TABLE CATEGORIA
(
  IdCategoria INT IDENTITY(1,1) NOT NULL, 
  Nombre VARCHAR(50) NOT NULL UNIQUE, 
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_Categoria)
);

CREATE TABLE PRENDA
(
  CodigoSku INT NOT NULL, 
  Talle VARCHAR(10) NOT NULL, 
  Color VARCHAR(50) NOT NULL,
  PrecioActual DECIMAL(10,2) NOT NULL,
  Stock INT NOT NULL CONSTRAINT CHK_PRENDA_Stock CHECK (Stock >= 0), 
  Modelo VARCHAR(50) NOT NULL,
  IdCategoria INT NOT NULL,
  CONSTRAINT PK_PRENDA PRIMARY KEY (Codigo_SKU),
  CONSTRAINT FK_PRENDA_CATEGORIA FOREIGN KEY (ID_Categoria) REFERENCES CATEGORIA(ID_Categoria)
    ON DELETE NO ACTION
    ON UPDATE CASCADE, 
  CONSTRAINT CHK_PRENDA_PrecioActual CHECK (Precio_Actual > 0)
);

CREATE TABLE ABONA_CON
(
  IdMetodo INT NOT NULL,
  NroComprobante INT NOT NULL,
  MontoAbonado DECIMAL(10,2) NOT NULL,
  CONSTRAINT PK_ABONA_CON PRIMARY KEY (ID_Metodo, Nro_Comprobante),
  CONSTRAINT FK_ABONA_CON_METODO_PAGO FOREIGN KEY (ID_Metodo) REFERENCES METODO_PAGO(ID_Metodo)
    ON DELETE NO ACTION
    ON UPDATE CASCADE,
  CONSTRAINT FK_ABONA_CON_VENTA FOREIGN KEY (Nro_Comprobante) REFERENCES VENTA(Nro_Comprobante)
    ON DELETE CASCADE
    ON UPDATE CASCADE, -- Faltaba una coma aquí en tu script original
  CONSTRAINT CHK_ABONA_CON_MontoAbonado CHECK (Monto_Abonado > 0)
);

CREATE TABLE CONTIENE
(
  NroComprobante INT NOT NULL,
  CodigoSku INT NOT NULL,
  PrecioHistorico DECIMAL(10,2) NOT NULL,
  Cantidad INT NOT NULL,
  CONSTRAINT PK_CONTIENE PRIMARY KEY (Nro_Comprobante, Codigo_SKU),
  CONSTRAINT FK_CONTIENE_VENTA FOREIGN KEY (Nro_Comprobante) REFERENCES VENTA(Nro_Comprobante)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  CONSTRAINT FK_CONTIENE_PRENDA FOREIGN KEY (Codigo_SKU) REFERENCES PRENDA(Codigo_SKU)
    ON DELETE NO ACTION
    ON UPDATE CASCADE, -- Faltaba una coma aquí en tu script original
  CONSTRAINT CHK_CONTIENE_PrecioHistorico CHECK (Precio_Historico > 0),
  CONSTRAINT CHK_CONTIENE_Cantidad CHECK (Cantidad > 0)
);


